_COVER_LETTER_STYLE_RULES = (
    "COVER LETTER STYLE — write like a senior engineer talking to a technical hiring manager.\n"
    "Follow every rule below. Violating these rules produces an unusable letter.\n\n"
    "--- PARAGRAPH ARCHITECTURE (each paragraph has one job) ---\n"
    "P1 — Company hook: Name what the company builds or does. Connect it to the "
    "candidate's domain expertise (fintech, trading, data, ML). One sentence max. "
    "Then state the role and why the candidate is specifically suited — mention one "
    "relevant technology from the job that the candidate already ships in. "
    'No narrative, no biography. Just: "I build X. Your Y role needs Z. I do Z."\n\n'
    "P2 — Technical credibility: Map 1-2 specific job requirements to concrete "
    "deliverables from the candidate's profile. Use exact numbers or project names "
    'where available. Structure: "You need [requirement from job]. '
    'I built [project] that [outcome — metric or scope]." '
    "No generic skill lists. If the candidate's profile has a relevant project, "
    "use it; otherwise pick the most relevant skill combination.\n\n"
    "P3 — Value proposition (forward-looking): Describe what the candidate will "
    "ship or improve in this role. NOT what they hope to learn. Use the job's "
    "own tech stack and domain. Frame it as: \"I'll bring [specific capability] "
    'to [specific problem the job posting describes]."\n\n'
    "P4 — Close: One sentence. Direct call to action. \"I'd welcome the chance "
    'to discuss how [specific skill] applies to [specific company challenge]."\n\n'
    "--- VOICE RULES ---\n"
    "1. Active voice. No passive constructions. Bad: 'Experience has been gained in…' "
    "Good: 'I built…', 'I shipped…', 'I designed…'\n"
    "2. Specific over general. Bad: 'I have experience with microservices.' "
    "Good: 'I maintain a 12-service FastAPI mesh handling 50K req/s.'\n"
    "3. No clichés. Banned phrases (zero tolerance): 'I am writing to apply', "
    "'I am excited to apply', 'I would love to', 'passionate about', "
    "'thrilled to', 'the opportunity to', 'I believe that', 'strong track record', "
    "'proven ability', 'team player'. If you use any of these the letter is garbage.\n"
    "4. No hedging. Bad: 'I think I could help with…' Good: 'I will improve…, I will design…\n"
    "5. Sentences under 20 words. Short and punchy.\n"
    "6. No em-dashes. No parentheses inside parentheses. "
    "No semicolons — use periods.\n"
    "7. No adjectives without evidence. 'Robust', 'scalable', 'cutting-edge' "
    "must be paired with a concrete system or number.\n\n"
    "--- LENGTH & STRUCTURE ---\n"
    "- Exactly 4 paragraphs.\n"
    "- Hard maximum 250 words total.\n"
    "- No salutation ('Dear Hiring Manager'). No sign-off ('Sincerely'). "
    "Just the body.\n"
    "- Do not repeat the candidate's name, role title, or company name "
    "more than once.\n"
)

