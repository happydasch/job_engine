def generate_readme_md(name: str, url: str, display_name: str) -> str:
    """Generate README.md for the scraper."""
    domain = urlparse(url).netloc
    return f"""# {display_name} Scraper

Scrapes job listings from [{display_name}]({url}).

## Configuration

| Field | Type | Default | Description |
|-------|------|---------|-------------|
| base_url | text | `{url}` | The base URL for the job board |
| pagination | number | 5 | Number of pages to scrape |

## Output

Returns an array of job objects with the standard Job Engine schema.

## Notes

- Target domain: {domain}
- Generated: {__import__('datetime').datetime.now().strftime('%Y-%m-%d')}
"""


def main():
    parser = argparse.ArgumentParser(
        description="Scaffold a new scraper package",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="Examples:\n  scaffold_scraper.py my_board https://example.com/jobs\n  scaffold_scraper.py --name my_board --url https://example.com/jobs",
    )
    parser.add_argument("name", nargs="?", help="Scraper name (lowercase, underscores)")
    parser.add_argument("url", nargs="?", help="Target URL of the job board")
    parser.add_argument("--name", dest="name_flag", help="Scraper name (alternative)")
    parser.add_argument("--url", dest="url_flag", help="Target URL (alternative)")
    parser.add_argument("--display", help="Display name (defaults to URL domain)")
    
    args = parser.parse_args()
    
    name = args.name or args.name_flag
    url = args.url or args.url_flag
    
    if not name or not url:
        parser.print_help()
        print("\nError: Both name and url are required.")
        sys.exit(1)
    
    name = sanitize_name(name)
    if not url.startswith(("http://", "https://")):
        url = "https://" + url
    
    domain = urlparse(url).netloc
    display_name = args.display or domain.replace("www.", "").split(".")[0].title()
    
    # Determine the scraper directory
    repo_root = Path(__file__).resolve().parent.parent
    scraper_dir = repo_root / "packages" / "job-engine-scrapers" / "scrapers" / name
    
    if scraper_dir.exists():
        print(f"✗ Scraper directory already exists: {scraper_dir}")
        sys.exit(1)
    
    # Create directory structure
    scraper_dir.mkdir(parents=True, exist_ok=True)
    
    # Write files
    files = {
        "package.json": generate_package_json(name, url, display_name),
        "index.js": generate_index_js(name, url, display_name),
        "README.md": generate_readme_md(name, url, display_name),
    }
    
    for filename, content in files.items():
        filepath = scraper_dir / filename
        filepath.write_text(content)
        print(f"  ✓ Created {filepath.relative_to(repo_root)}")
    
    print(f"\n✓ Scraper '{name}' scaffolded at {scraper_dir.relative_to(repo_root)}")
    print(f"\nNext steps:")
    print(f"  1. Implement the scraping logic in {scraper_dir.relative_to(repo_root) / 'index.js'}")
    print(f"  2. Install the scraper: make scraper-install ID={name}")
    print(f"  3. Test the scraper: cd packages/job-engine-scrapers && node run.js --scraper {name}")


if __name__ == "__main__":
    main()
